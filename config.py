"""
config.py — 設定ファイル

【このファイルの役割】
部員が「ちょっと変えたい」と思いそうな値を、ここ1か所にまとめています。
表示件数・時限の時刻・自動削除の間隔・ポート番号などを変えたいときは、
基本的にこのファイルだけを書き換えれば済むようにしてあります。

変更したら、サーバーを再起動（Ctrl+C で止めて `uv run app.py`）すると反映されます。
"""

from pathlib import Path

# ---------------------------------------------------------------------------
# サーバー
# ---------------------------------------------------------------------------

# サーバーが待ち受けるポート番号。
# スマホからは http://<Mac miniのIP>:<PORT>/ でアクセスします。
PORT = 8000

# "0.0.0.0" にすると、同じ Wi-Fi のスマホなど「外の端末」からもつながります。
# "127.0.0.1" にすると Mac mini 自身からしか開けなくなるので注意。
HOST = "0.0.0.0"

# QR コードに埋め込む URL を手動で固定したいときに設定します。
# 例: PUBLIC_URL = "http://192.168.1.20:8000/"
# None のままなら、サーバー起動時の IP アドレスから自動で作ります。
PUBLIC_URL = None

# ---------------------------------------------------------------------------
# データ保存
# ---------------------------------------------------------------------------

# このプロジェクトのフォルダ（config.py が置いてある場所）
BASE_DIR = Path(__file__).resolve().parent

# 予定を保存する SQLite ファイルの場所。フォルダがなければ自動で作ります。
DB_PATH = BASE_DIR / "data" / "events.db"

# 終わった予定（毎年繰り返さないもの）をまとめて削除する間隔（秒）。
# 3600 = 1時間ごと。サーバー起動時にも1回実行されます。
CLEANUP_INTERVAL_SECONDS = 60 * 60

# ---------------------------------------------------------------------------
# モニター画面（/display）
# ---------------------------------------------------------------------------

# 「今後の予定」に表示する件数
UPCOMING_COUNT = 7

# 「重要な予定」（今後の予定に入りきらなかった重要予定）に表示する件数
IMPORTANT_COUNT = 3

# モニター画面が予定を取り直す間隔（秒）。
# 短くすると入力がすぐ反映されますが、短すぎても意味はないので数十秒で十分です。
REFRESH_SECONDS = 30

# ---------------------------------------------------------------------------
# 時限（アナログ時計の中に表示する）
# ---------------------------------------------------------------------------

# (開始時刻, 終了時刻, 表示する文字) の順に並べます。時刻は "時:分" の24時間表記。
# 「開始時刻ちょうど」からその表示になり、「終了時刻ちょうど」で次の表示に切り替わります。
# どれにも当てはまらない時間帯は NO_PERIOD_LABEL が表示されます。
# 曜日は見ないので、土日・祝日も平日と同じように表示されます。
PERIODS = [
    ("9:00", "10:40", "1限"),
    ("10:40", "10:55", "休憩時間"),
    ("10:55", "12:35", "2限"),
    ("12:35", "13:20", "休憩時間"),
    ("13:20", "15:00", "3限"),
    ("15:00", "15:15", "休憩時間"),
    ("15:15", "16:55", "4限"),
    ("16:55", "17:10", "休憩時間"),
    ("17:10", "18:50", "5限"),
]

# 上の時間帯のどれにも当てはまらないときの表示
NO_PERIOD_LABEL = "no schedule"
